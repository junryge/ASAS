# ============================================================
# ★ reason 텍스트 → 발동 컬럼 (evt_col, raw_full, area, rule) 추출
#
# reason 예시:
#   "hot_area=M16HUB; S3확정; 발동: M16HUB[R-A'(AVGTOTALTIME1MIN=6.34분),
#    R-D(FAB저장=0.0%,STB=100.0%)]; M16B[R-D(OHT=98.7%),SLA(47.7%4분초과)]"
# ============================================================
_AREA_RE = re.compile(r"(M16HUB|M14B|M14|M16A|M16B|M16_PKT|M16_WT|M16)\[([^\]]+)\]")


def parse_reason_pairs(reason):
    """발동이벤트 reason → [(evt_col, raw_full, area, rule)] 발동 컬럼 추출.

    동일 컬럼 중복 제거. 영역 순서 유지.
    """
    out = []
    seen = set()

    def add(evt_col, raw_full, area, rule):
        if evt_col in seen: return
        seen.add(evt_col)
        out.append((evt_col, raw_full, area, rule))

    for m in _AREA_RE.finditer(reason or ''):
        area, body = m.group(1), m.group(2)
        # R-A' / R-A_sus — AVGTOTALTIME1MIN / AVGLOADTIME1MIN
        if "AVGTOTALTIME1MIN" in body or "AVGLOADTIME1MIN" in body or "R-A'" in body or "R-A_sus" in body:
            evt = f"{area}_ra"
            if evt in EVT_TO_RAW:
                add(evt, EVT_TO_RAW[evt], area, "R-A")
        # R-D M16HUB FAB / STB
        if area == 'M16HUB' and ('FAB저장' in body or 'FABSTORAGE' in body):
            add('M16HUB_rd_fab', RD_FAB_COL, area, "R-D(FAB)")
        if area == 'M16HUB' and 'STB=' in body:
            add('M16HUB_stb_util', RD_STB_COL, area, "R-D(STB)")
        # R-D OHT (M14/M14B/M16A/M16B)
        if ('OHT=' in body or 'OHTUTIL' in body) and area in RD_OHT_COL and area != 'M16HUB':
            evt = f"{area}_rd_oht"
            add(evt, RD_OHT_COL[area], area, "R-D(OHT)")
        # SLA
        if ('SLA(' in body or 'TRANSPORT4MIN' in body) and area in SLA_COL:
            evt = f"sla_{area}"
            add(evt, SLA_COL[area], area, "SLA")
        # Sorter
        if ('Sorter(' in body or 'SORTERWAIT' in body) and area in SORTER_COL:
            evt = f"sorter_{area}"
            add(evt, SORTER_COL[area], area, "Sorter")
        # R-C' 리프터 (M16HUB 전용) — reason 키워드 매칭만 유지
        if area == 'M16HUB' and '역증가' in body:
            add('M16HUB_rev_count', RC_REPRESENTATIVE, area, "R-C'")
    return out


# ============================================================
# ★ 사건단위 relation 텍스트 → 발동 컬럼 추출
#
# relation 예시:
#   "[M16HUB R-A'] M16HUB.QUE.TIME.AVGTOTALTIME1MIN=6.34분 (기준 5.0분) |
#    [M16HUB R-D] FABSTORAGERATIO=92.3% (기준 90%)"
# → relation 은 raw 풀네임 직접 포함
# ============================================================
_RAW_COL_RE = re.compile(r"\b([A-Z][A-Z0-9_]+(?:\.[A-Z0-9_]+){2,})\b")


def parse_relation_pairs(relation):
    """사건단위 relation → [(evt_col, raw_full, area, rule)].

    relation 에는 raw 풀네임이 직접 들어 있어 텍스트 그대로 추출.
    """
    out = []
    seen = set()
    text = relation or ''
    # raw 풀네임 직접 추출
    for raw in _RAW_COL_RE.findall(text):
        if raw in RAW_TO_EVT and raw not in seen:
            seen.add(raw)
            evt = RAW_TO_EVT[raw]
            area = raw.split('.')[0]
            # 룰 식별 (텍스트 패턴)
            rule = "?"
            for rid in ("R-A'", "R-A_sus", "R-A", "R-B_fast", "R-B", "R-C'", "R-C",
                        "R-D", "SLA", "Sorter", "MAXCAPA"):
                if f"[{area} {rid}]" in text or rid in text:
                    rule = rid; break
            out.append((evt, raw, area, rule))
    # 리프터 (한글 키워드 — relation 안의 '역증가'/'감소' 텍스트만 매칭에 사용)
    if '리프터' in text and '역증가' in text and 'M16HUB_rev_count' not in seen:
        seen.add('M16HUB_rev_count')
        out.append(('M16HUB_rev_count', RC_REPRESENTATIVE, 'M16HUB', "R-C'"))
    return out


