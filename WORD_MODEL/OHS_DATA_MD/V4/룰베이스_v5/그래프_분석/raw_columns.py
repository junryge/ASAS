def friendly_label(evt_col):
    if evt_col.endswith('_ra'):
        a = evt_col.replace('_ra', ''); return f"{a} 반송시간 (분)"
    if evt_col == 'M16HUB_rd_fab':    return "M16HUB FAB 저장율 (%)"
    if evt_col == 'M16HUB_stb_util':  return "M16HUB STB 저장율 (%)"
